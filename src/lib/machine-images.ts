export const DEFAULT_MACHINE_IMG = MACHINE_IMG["John Deere 5310"];

/**
 * Resolves a 100% accurate photograph for any tractor model or farm implement.
 */
export function getMachineImage(name?: string, category?: string): string {
  if (!name && !category) return DEFAULT_MACHINE_IMG;
  const raw = `${name || ""} ${category || ""}`.toLowerCase();

  // 1. Direct name match
  for (const [key, url] of Object.entries(MACHINE_IMG)) {
    if (raw.includes(key.toLowerCase())) {
      return url;
    }
  }

  // 2. Category specific fallbacks
  if (raw.includes("harvester") || raw.includes("combine")) return MACHINE_IMG["harvester"];
  if (raw.includes("rotavator") || raw.includes("tiller")) return MACHINE_IMG["rotavator"];
  if (raw.includes("plough") || raw.includes("cultivator")) return MACHINE_IMG["cultivator"];
  if (raw.includes("seeder") || raw.includes("drill") || raw.includes("transplanter")) return MACHINE_IMG["seeder"];
  if (raw.includes("sprayer") || raw.includes("drip")) return MACHINE_IMG["sprayer"];
  if (raw.includes("thresher")) return MACHINE_IMG["thresher"];

  return DEFAULT_MACHINE_IMG;
}

