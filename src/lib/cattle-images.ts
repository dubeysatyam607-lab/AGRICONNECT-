export function getCattleImage(nameOrBreed?: string): string {
  if (!nameOrBreed) return CATTLE_IMAGE_MAP.cattle;
  const raw = nameOrBreed.toLowerCase().trim();

  for (const [key, url] of Object.entries(CATTLE_IMAGE_MAP)) {
    if (raw.includes(key)) return url;
  }

  const tokens = raw.split(/\s+/).filter((t) => t.length >= 3);
  for (const token of tokens) {
    if (CATTLE_IMAGE_MAP[token]) {
      return CATTLE_IMAGE_MAP[token];
    }
  }

  if (raw.includes("buffalo") || raw.includes("bhains") || raw.includes("murrah")) {
    return CATTLE_IMAGE_MAP.buffalo;
  }
  if (raw.includes("bull") || raw.includes("bail") || raw.includes("saand")) {
    return CATTLE_IMAGE_MAP.bull;
  }
  if (raw.includes("calf") || raw.includes("bachhda") || raw.includes("bachhiya")) {
    return CATTLE_IMAGE_MAP.calf;
  }
  if (raw.includes("goat") || raw.includes("bakri")) {
    return CATTLE_IMAGE_MAP.goat;
  }

  return CATTLE_IMAGE_MAP.cow;
}

