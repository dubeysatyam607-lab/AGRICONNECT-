export function getCropCategory(cropName?: string): string {
  if (!cropName) return "Cereals";
  const name = cropName.toLowerCase().trim();

  if (
    name.includes("cumin") ||
    name.includes("jeera") ||
    name.includes("turmeric") ||
    name.includes("haldi") ||
    name.includes("coriander") ||
    name.includes("cardamom") ||
    name.includes("clove") ||
    name.includes("cinnamon") ||
    name.includes("fennel") ||
    name.includes("fenugreek")
  ) {
    return "Spices";
  }

  if (
    name.includes("gram") ||
    name.includes("chana") ||
    name.includes("moong") ||
    name.includes("urad") ||
    /\btur\b/.test(name) ||
    name.includes("toor") ||
    name.includes("arhar") ||
    name.includes("lentil") ||
    name.includes("masur") ||
    name.includes("masoor")
  ) {
    return "Pulses";
  }

  if (
    name.includes("wheat") ||
    name.includes("rice") ||
    name.includes("paddy") ||
    name.includes("maize") ||
    name.includes("corn") ||
    name.includes("barley") ||
    name.includes("jowar") ||
    name.includes("bajra")
  ) {
    return "Cereals";
  }

  if (
    name.includes("soybean") ||
    name.includes("mustard") ||
    name.includes("sarson") ||
    name.includes("groundnut") ||
    name.includes("sunflower") ||
    name.includes("sesame") ||
    name.includes("til")
  ) {
    return "Oilseeds";
  }

  if (
    name.includes("cotton") ||
    name.includes("sugarcane") ||
    name.includes("jute") ||
    name.includes("tobacco") ||
    name.includes("tea") ||
    name.includes("coffee")
  ) {
    return "Commercial";
  }

  if (
    name.includes("tomato") ||
    name.includes("onion") ||
    name.includes("potato") ||
    name.includes("chilli") ||
    name.includes("garlic") ||
    name.includes("ginger") ||
    name.includes("cabbage") ||
    name.includes("cauliflower") ||
    name.includes("brinjal") ||
    name.includes("bhindi") ||
    name.includes("okra")
  ) {
    return "Vegetables";
  }

  if (
    name.includes("banana") ||
    name.includes("apple") ||
    name.includes("mango") ||
    name.includes("orange") ||
    name.includes("pomegranate") ||
    name.includes("grapes") ||
    name.includes("guava") ||
    name.includes("papaya") ||
    name.includes("watermelon")
  ) {
    return "Fruits";
  }

  return "Cereals";
}

export function getCropImage(cropName?: string): string {
  if (!cropName) return CATEGORY_CROP_IMAGES.default;
  const lower = cropName.toLowerCase().trim();

  for (const [key, url] of Object.entries(CROP_IMAGE_MAP)) {
    if (lower.includes(key)) return url;
  }
  return CATEGORY_CROP_IMAGES.default;
}

export function getCropBackupImage(cropName?: string): string {
  return getCropImage(cropName);
}
